package ioutil

import (
	"context"
	"io"
)

// NewContextReader returns a reader that returns ctx.Err() before each Read
// once ctx is done. A Read already blocked in r is not interrupted.
func NewContextReader(ctx context.Context, r io.Reader) io.Reader {
	return &contextReader{ctx: ctx, r: r}
}

type contextReader struct {
	ctx context.Context
	r   io.Reader
}

func (c *contextReader) Read(p []byte) (int, error) {
	if err := c.ctx.Err(); err != nil {
		return 0, err
	}
	return c.r.Read(p)
}
